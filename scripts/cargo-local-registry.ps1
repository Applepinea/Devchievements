# scripts/cargo-local-registry.ps1
#
# Usage (after starting scripts/local-crates-proxy.mjs):
#   . .\scripts\cargo-local-registry.ps1 -Port 8787
#
# WHY THIS EXISTS (host workaround, NOT part of the product)
# ---------------------------------------------------------
# cargo on Windows links libcurl with the schannel TLS backend. On this host the
# schannel credential chain is broken (SEC_E_NO_CREDENTIALS), so cargo cannot
# reach crates.io at all. Node.js uses its own OpenSSL stack and works.
#
# We therefore run a local sparse-registry proxy (scripts/local-crates-proxy.mjs)
# and point cargo at it with a source replacement. Cargo then only ever talks
# plain HTTP to 127.0.0.1 and never opens a schannel socket.
#
# SCOPE
# -----
# This writes .cargo/config.toml inside the repository only. It never touches the
# user's global cargo config. Delete the file to revert.
#
# Keep this file ASCII-only (Windows PowerShell 5.1 reads .ps1 as ANSI).

param(
    [int]$Port = 8787
)

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
$cargoDir = Join-Path $repoRoot '.cargo'
if (-not (Test-Path $cargoDir)) {
    New-Item -ItemType Directory -Path $cargoDir -Force | Out-Null
}

$configPath = Join-Path $cargoDir 'config.toml'

$content = @"
# GENERATED by scripts/cargo-local-registry.ps1 -- do not edit by hand.
#
# Host workaround: this machine's schannel TLS is broken, so cargo cannot use
# https. We replace crates.io with a local sparse-registry proxy served by
# scripts/local-crates-proxy.mjs (Node.js/OpenSSL).
#
# To revert: delete this file.

[source.crates-io]
replace-with = "local-proxy"

[source.local-proxy]
registry = "sparse+http://127.0.0.1:$Port/index/"

[net]
retry = 3

[registries.crates-io]
protocol = "sparse"
"@

Set-Content -Path $configPath -Value $content -Encoding ASCII
Write-Host "cargo-local-registry.ps1: wrote $configPath"
Write-Host "cargo-local-registry.ps1: registry -> sparse+http://127.0.0.1:$Port/index/"
Write-Host "cargo-local-registry.ps1: make sure the proxy is running:"
Write-Host "    node scripts/local-crates-proxy.mjs --port $Port"
